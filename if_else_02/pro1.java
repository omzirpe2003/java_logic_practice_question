
/*
 * Range Check: Write a program to check whether the given number is in the range of 1 to 1000 or not. (Use hardcoded values).
 */

class Pro1{
	public static void main(String[]args){
		int x=100;
		if (x>=1 && x<=1000){
			System.out.println("In Range");
		}else {
			System.out.println("Not In Range");
			
		}
	}
}

