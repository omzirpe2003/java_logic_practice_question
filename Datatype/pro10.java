

/*Write a program to print the characters using given ASCII values:
67, 79, 82, 69, 50, 87, 69, 66
*/

class Pro10{
	public static void main(String[]args){
		char char1=67;
		char char2=79;
		char char3=82;
		char char4=69;
		char char5=50;
		char char6=87;
		char char7=66;

		System.out.println("67: "+char1);
		System.out.println("79: "+char2);
		System.out.println("82: "+char3);
		System.out.println("69: "+char4);
		System.out.println("50: "+char5);
		System.out.println("87: "+char6);
		System.out.println("66: "+char7);
	}
}
