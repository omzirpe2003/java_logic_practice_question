
/*
 * 9. Day of Week

Write a program to check the day number (1–7) and print the corresponding day of the week.

1 → Monday
7 → Sunday
Invalid → print error message

*/

class Pro9{
	public static void main(String[]args){
		int x=2;
		if(x==1){
			System.out.println("Monday");
		}else if(x==2){

			System.out.println("Tusdat");
		}else if(x==3){
			System.out.println("Wenasday");

		}else if(x==4){
			System.out.println("Thusday");

		}else if(x==5){
			System.out.println("Friday");

		}else if(x==6){
			System.out.println("Saterday");

		}else if(x==7){
			System.out.println("Sunday");

		}
	}
}
